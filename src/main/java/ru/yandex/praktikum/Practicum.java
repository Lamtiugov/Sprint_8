package ru.yandex.praktikum;


public class Practicum {

    public static void main(String[] args) {
        /*
             В этом методе заложи логику работы с классом Account.
             Нужно создать экземпляр класса Account: в качестве аргумента передать тестируемое имя
             и вызвать метод, который проверяет, можно ли использовать фамилию и имя для печати на банковской карте.
         */
        Account validator = new Account();

        String[] testCases = {
                "Тимоти Шаламе",      // можно
                "ТимотейШевроле",     // нельзя (нет пробела)
                "  Иван Иванов",      // нельзя (пробел в начале)
                "Иван Иванов  ",      // нельзя (пробел в конце)
                "А Б",                // можно (3 символа, один пробел)
                "ОченьДлинноеИмя Фамилия", // нельзя (>19 символов)
                "Анна",               // нельзя (нет пробела)
                " ",                  // нельзя (только пробел, длина 1)
                "Имя Фамилия Фамилия" // нельзя (два пробела)
        };

        for (String test : testCases) {
            boolean result = validator.checkNameToEmboss(test);
            System.out.println("\"" + test + "\" -> " + (result ? "можно" : "нельзя"));
        }
    }

}